#!/usr/bin/env node
// Build the Staff Hub brand download library.
//
//   node scripts/build-brand-library.mjs
//
// Reads the master brand library (which lives OUTSIDE this repo, see
// 00_Program/brand-notes.md), copies the web-resolution PNG and JPG of each
// mark into shared/assets/brand/library/, and writes the manifest that the
// Brand page renders from.
//
// Only PNG and JPG are copied. EPS and PSD stay in the master library: staff
// cannot open them and they would bloat the repo.
//
// Re-run this whenever Communications updates the master library.

import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MASTER = process.env.CF_BRAND_ASSETS
  ?? path.join(os.homedir(), "Projects/cornerstone/brand-assets");
const OUT = path.join(REPO, "shared/assets/brand/library");
const MANIFEST = path.join(REPO, "tools/staff-hub/brand-library.js");

// Which folders to pull, and how to name what comes out of them.
const GROUPS = [
  { id: "wordmark", title: "Cornerstone logo",
    blurb: "The full wordmark. Use this first unless space forces the icon.",
    src: "Logos/Cornerstone Full Logo" },
  { id: "icon", title: "Cornerstone icon",
    blurb: "The mark on its own. For avatars, favicons and tight spaces.",
    src: "Icons/Cornerstone" },
  { id: "campus", title: "Campus logos",
    blurb: "One per campus. Use the campus mark for campus-specific material.",
    src: "Logos/Campus Logos" },
  { id: "campus-icon", title: "Campus icons",
    blurb: "The icon form of each campus mark.",
    src: "Icons/Campus" },
  { id: "ministry", title: "Ministry logos",
    blurb: "One per ministry team.",
    src: "Logos/Ministry Logos" },
];

// The campus files are named by abbreviation. Expand them to the words that
// appear in the artwork itself, so staff can find the one they need.
// Note: the DV artwork reads DANVILLE, while the campus list calls it San
// Ramon Valley. Flagged for Communications; the label here follows the file.
const LABELS = {
  BW: "Brentwood", DV: "Danville", HW: "Hayward",
  LV: "Livermore", WC: "Walnut Creek",
  // "Horziontal" is misspelled in the source filenames. Fixed here so staff
  // do not see it; the master library still has the typo.
  "HORZIONTAL BOLD": "Horizontal",
  BOLD: "Stacked",
  CORNERSTONE: "Outline",
};

// "CF-Guest Services-WHITE" -> { name: "Guest Services", variant: "white" }
function parse(file) {
  const base = path.basename(file, path.extname(file));
  const m = base.match(/-(BLACK|WHITE|BLUE)$/i);
  const variant = m ? m[1].toLowerCase() : "default";
  let name = (m ? base.slice(0, m.index) : base)
    .replace(/^CF[-\s]*/i, "")
    .replace(/\bLogo\b/gi, "")
    .replace(/\bIcon\b/gi, "")
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!name) name = "Cornerstone";
  name = LABELS[name.toUpperCase()] ?? name;
  return { name, variant };
}

// Marks that are not offered for download. Pulled 2026-09-20 at Ryan's
// direction. Excluding them here rather than deleting files by hand means a
// re-run of this script does not quietly bring them back.
const EXCLUDE = new Set(["Hayward", "Danville"]);

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

if (!fs.existsSync(MASTER)) {
  console.error(`\n  Master brand library not found at:\n    ${MASTER}\n`);
  console.error("  Set CF_BRAND_ASSETS if it lives somewhere else.\n");
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const manifest = [];
let copied = 0, bytes = 0, skipped = 0;

for (const g of GROUPS) {
  const assets = new Map();          // key -> { name, variant, png, jpg }
  for (const [fmt, ext] of [["PNG", ".png"], ["JPG", ".jpg"]]) {
    const dir = path.join(MASTER, g.src, fmt, "Web");
    if (!fs.existsSync(dir)) continue;
    for (const file of fs.readdirSync(dir)) {
      if (path.extname(file).toLowerCase() !== ext) continue;
      const { name, variant } = parse(file);
      if (EXCLUDE.has(name)) { skipped++; continue; }
      const key = `${slug(name)}-${variant}`;
      const outName = `${g.id}-${key}${ext}`;
      fs.mkdirSync(path.join(OUT, g.id), { recursive: true });
      const dest = path.join(OUT, g.id, outName);
      fs.copyFileSync(path.join(dir, file), dest);
      bytes += fs.statSync(dest).size;
      copied++;
      const a = assets.get(key) ?? { name, variant };
      a[ext.slice(1)] = `${g.id}/${outName}`;
      assets.set(key, a);
    }
  }
  const list = [...assets.values()].sort((a, b) =>
    a.name.localeCompare(b.name) || a.variant.localeCompare(b.variant));
  if (list.length) manifest.push({ ...g, assets: list });
}

const body = `// GENERATED by scripts/build-brand-library.mjs. Do not edit by hand.
// Source: the master brand library outside this repo. Re-run the script when
// Communications updates it.
//
// Paths are relative to shared/assets/brand/library/.

export const BRAND_LIBRARY = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(MANIFEST, body);

console.log("");
console.log(`  Copied ${copied} files, ${(bytes / 1024 / 1024).toFixed(1)} MB`);
for (const g of manifest) console.log(`    ${g.title.padEnd(20)} ${g.assets.length} marks`);
if (skipped) console.log(`  Skipped ${skipped} files on the exclude list: ${[...EXCLUDE].join(", ")}`);
console.log(`  Manifest: ${path.relative(REPO, MANIFEST)}`);
console.log("");
